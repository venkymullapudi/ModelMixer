"""Pre-measure the Atlas "Which knobs transfer across seeds?" table on every toy and store it with the app.

Usage:
  python3 scripts/transfer_snapshot.py           # measure all toys (about 70 s) and write js/transfer-snapshot.js
  python3 scripts/transfer_snapshot.py --check   # exit 1 if the engine changed since the snapshot was taken (instant)

The snapshot records a SHA-256 of the engine sources (the files that decide every number). CI runs --check, so a
change to training, merging or the transfer verdicts can't ship with a stale snapshot.
Needs: pip install playwright (local: your Google Chrome; PW_CHANNEL="" for Playwright's Chromium). Rebuild dist/ first.
"""
import datetime, hashlib, json, os, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
ENGINE = ["js/nn.js", "js/data.js", "js/methods.js", "js/merge.js", "js/lab.js"]
OUT = ROOT / "js" / "transfer-snapshot.js"


def engine_hash():
    h = hashlib.sha256()
    for f in ENGINE:
        h.update(f.encode() + b"\0" + (ROOT / f).read_bytes() + b"\0")
    return h.hexdigest()


def stored_hash():
    if not OUT.exists():
        return None
    m = re.search(r'"engineHash":\s*"([0-9a-f]{64})"', OUT.read_text())
    return m.group(1) if m else None


if "--check" in sys.argv:
    now, then = engine_hash(), stored_hash()
    if now != then:
        print(f"js/transfer-snapshot.js is stale (engine {now[:12]} vs snapshot {str(then)[:12]}).")
        print("Run: python3 scripts/bundle.py && python3 scripts/transfer_snapshot.py, then commit.")
        sys.exit(1)
    print(f"transfer snapshot matches the engine ({now[:12]})")
    sys.exit(0)

from playwright.sync_api import sync_playwright  # noqa: E402

READY = "() => { const T = window.ModelMixer && window.ModelMixer.trained; return !!(T && T.experts) && !/Training/.test(document.querySelector('#statusText').textContent); }"
with sync_playwright() as p:
    b = p.chromium.launch(channel=os.environ.get("PW_CHANNEL", "chrome") or None, headless=True)
    ctx = b.new_context(viewport={"width": 1440, "height": 900})
    ctx.add_init_script("try { localStorage.clear(); localStorage.setItem('modelmixer:tour', 'done') } catch (e) {}")
    pg = ctx.new_page()
    errs = []
    pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.on("console", lambda m: errs.append(m.text) if m.type == "error" else None)
    pg.goto((ROOT / "dist/modelmixer.html").as_uri())
    pg.wait_for_function(READY, timeout=120000)
    pg.click('[data-tab="atlas"]')
    pg.click("#runTransfer")
    # wait for the live table (the pre-measured snapshot also renders a table, with class tr-x)
    pg.wait_for_function("() => !!document.querySelector('#transfer table.tr-table:not(.tr-x)')", timeout=600000)
    while pg.locator("[data-tr-toy]").count():
        toy = pg.locator("[data-tr-toy]").first.get_attribute("data-tr-toy")
        pg.click(f'[data-tr-toy="{toy}"]')
        pg.wait_for_function(f"() => !document.querySelector('[data-tr-toy=\"{toy}\"]')", timeout=900000)
        print("measured", toy)
    entries = pg.evaluate("() => window.ModelMixer.transferEntries()")
    b.close()

if errs:
    print("page errors:", errs)
    sys.exit(1)
expected = 7
if len(entries) < expected or any(not e["rows"] for e in entries):
    print(f"incomplete measurement ({len(entries)} of {expected} toys): not writing the snapshot")
    sys.exit(1)
order = {sid: i for i, sid in enumerate(["two", "three", "overlap", "strangers", "hard", "digits", "digits-conflict"])}
entries.sort(key=lambda e: order.get(e["scenario"], 99))
snap = {"seeds": 5, "date": datetime.date.today().isoformat(), "engineHash": engine_hash(), "entries": entries}
OUT.write_text("/* Generated by scripts/transfer_snapshot.py: do not edit. Pre-measured Atlas knob-transfer table, every toy × 5 seeds. */\n"
               "(function () {\n  const root = typeof window !== 'undefined' ? window : globalThis;\n  const MM = (root.MM = root.MM || {});\n"
               f"  MM.TRANSFER_SNAPSHOT = {json.dumps(snap, ensure_ascii=False)};\n}})();\n")
print(f"wrote {OUT} ({len(entries)} toys, {sum(len(e['rows']) for e in entries)} rows)")
